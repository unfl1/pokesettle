import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

interface FontSubset { file: string; unicodeRange: string }

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const subsets = JSON.parse(fs.readFileSync(path.join(root, 'src/styles/pretendard-subsets.json'), 'utf8')) as FontSubset[];
const check = process.argv.includes('--check');

if (subsets.length !== 92 || new Set(subsets.map(subset => subset.file)).size !== 92) {
  throw new Error('Expected 92 distinct Pretendard 1.3.9 subsets');
}

// next/font calls and their options must be static for Next.js to compile them.
const definitions = subsets.map((subset, index) => {
  if (subset.file !== `/fonts/pretendard/1.3.9/PretendardVariable.subset.${index}.woff2`
    || !/^U\+[0-9a-f?]+(?:-[0-9a-f]+)?(?:, U\+[0-9a-f?]+(?:-[0-9a-f]+)?)*$/i.test(subset.unicodeRange)
    || !fs.existsSync(path.join(root, 'public', subset.file))) {
    throw new Error(`Invalid font subset: ${index}`);
  }
  const isCommon = index === 91;
  return `const subset${index} = localFont({
  src: '../../public${subset.file}',
  variable: '--font-pretendard${isCommon ? '' : `-${index}`}',
  weight: '45 920',
  style: 'normal',
  display: 'swap',
  preload: false,
  ${isCommon ? "fallback: ['Arial', 'sans-serif']," : 'adjustFontFallback: false,'}
  declarations: [{ prop: 'unicode-range', value: '${subset.unicodeRange}' }],
});`;
});

const fontSource = `// Generated by scripts/generate-fonts.ts; edit the subset manifest and regenerate.
// Pretendard 1.3.9 · SIL OFL 1.1 · docs/guides/DATA_SOURCES.md
import localFont from 'next/font/local';

${definitions.join('\n\n')}

// Keep every subset ahead of the common subset's metric-adjusted Arial fallback.
export const pretendard = {
  variable: [
${subsets.map((_, index) => `    subset${index}.variable,`).join('\n')}
  ].join(' '),
};
`;
const cssPath = path.join(root, 'src/globals.css');
const css = fs.readFileSync(cssPath, 'utf8');
const fontStack = subsets.map((_, index) => `var(--font-pretendard${index === 91 ? '' : `-${index}`})`).join(', ');
if ((css.match(/--font-sans:[^;]+;/g) ?? []).length !== 1) {
  throw new Error('Expected one Tailwind --font-sans declaration');
}

for (const [file, content] of [
  [path.join(root, 'src/app/fonts.ts'), fontSource],
  [cssPath, css.replace(/--font-sans:[^;]+;/, `--font-sans: ${fontStack}, Arial, sans-serif;`)],
]) {
  if (fs.readFileSync(file, 'utf8') === content) continue;
  if (check) throw new Error(`Regenerate fonts: ${file}`);
  fs.writeFileSync(file, content);
}
console.log(`Validated ${subsets.length} next/font/local subsets${check ? ' (unchanged)' : ''}`);
